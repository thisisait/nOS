#!/usr/bin/env python3
"""Generate the model catalog: every backend and model, with badges derived from
the files that already decide them.

Writes state/genome/model-catalog.yml, one row per (backend, model) and nothing
else. Its inputs are state/habitat/llm-backends.yml (the backends, residency,
local, the ollama ladder), state/habitat/processors.yml (whether a processor
works in the EU) and state/habitat/models.yml (cloud model ids, caps, list
prices). A backend that has no named model gets one row with `model: null`,
because its model id comes from the env names in `model_env` at run time.

Display only. binding.rs and Wing's BindingResolver decide what may serve, and
a badge never changes that. The EU badge is true only when the processor
record says eu_processing true AND the backend's residency.eu is true. A
missing record shows as null (unassessed). Quality, latency and digest stay
`unassessed` until the nos-assay snapshot is vendored (row
model-catalog-with-quality, slice 2). No network.

Usage:
    python3 tools/model-catalog-gen.py            # write state/genome/model-catalog.yml
    python3 tools/model-catalog-gen.py --check    # exit 1 if the file is stale or an input is refused
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
HABITAT = REPO / "state" / "habitat"
TARGET = REPO / "state" / "genome" / "model-catalog.yml"
HEADER = ("# GENERATED by tools/model-catalog-gen.py from state/habitat/{llm-backends,processors,models}.yml.\n"
          "# Do not edit: change an input and rerun (tools/regenerate.py). Display only; binding.rs decides.\n")
PRICE_KEYS = {"in", "out", "currency", "source_url", "as_of"}
CAP_KEYS = {"thinking", "vision", "tools", "context"}


def _load(name: str) -> dict:
    return yaml.safe_load((HABITAT / name).read_text(encoding="utf-8")) or {}


def _refuse(msg: str) -> None:
    print(f"model-catalog-gen: {msg}", file=sys.stderr)
    raise SystemExit(1)


def _model_rows(backends: dict, models: list) -> dict[str, list[dict]]:
    """backend -> its model rows from models.yml, each checked. A refusal names the row."""
    out: dict[str, list[dict]] = {}
    for i, m in enumerate(models):
        where = f"models.yml row {i} ({m.get('backend')}/{m.get('model')})" if isinstance(m, dict) else f"models.yml row {i}"
        if not isinstance(m, dict) or not m.get("backend") or not m.get("model"):
            _refuse(f"{where}: needs backend and model")
        if m["backend"] not in backends:
            _refuse(f"{where}: backend {m['backend']!r} is not in llm-backends.yml")
        if extra := set(m) - {"backend", "model", "caps", "price"}:
            _refuse(f"{where}: unknown keys {sorted(extra)}")
        price = m.get("price")
        if price is not None:
            if not isinstance(price, dict) or set(price) - PRICE_KEYS:
                _refuse(f"{where}: price takes only {sorted(PRICE_KEYS)}")
            if not str(price.get("source_url") or "").startswith("https://") or not price.get("as_of"):
                _refuse(f"{where}: a price needs source_url (https) and as_of")
        caps = m.get("caps")
        if caps is not None and (not isinstance(caps, dict) or set(caps) - CAP_KEYS):
            _refuse(f"{where}: caps take only {sorted(CAP_KEYS)}")
        out.setdefault(m["backend"], []).append(m)
    return out


def build() -> dict:
    backends = _load("llm-backends.yml").get("backends") or {}
    processors = _load("processors.yml").get("processors") or {}
    named = _model_rows(backends, _load("models.yml").get("models") or [])
    rows = []
    for name in sorted(backends):
        b = backends[name]
        local = bool(b.get("local"))
        res = b.get("residency") or {}
        token = b.get("processor_match")
        rec = processors.get(token)
        eu = None if rec is None or rec.get("eu_processing") is None else bool(rec["eu_processing"] and res.get("eu") is True)
        listed = [{"model": m} for m in (b.get("sizes_b") or {}).values()] + named.get(name, [])
        for m in listed or [{"model": None}]:
            price = m.get("price")
            if price is None and local:
                price = {"in": 0, "out": 0, "note": "local: electricity not metered"}
            rows.append({
                "id": name if m["model"] is None else f"{name}/{m['model']}",
                "backend": name,
                "model": m["model"],
                "model_env": None if m["model"] else b.get("model_env"),
                "protocol": b.get("protocol"),
                "local": local,
                "residency": {"country": res.get("country"), "eu": res.get("eu")},
                "processor": {"name": token, "record": rec is not None,
                              "verified": bool(rec and rec.get("verified_on"))},
                "badges": {"eu": eu, "local": local},
                "caps": m.get("caps"),
                "price": price,
                "latency": "unassessed",
                "digest": "unassessed",
                "quality": "unassessed",
            })
    return {"version": 1, "rows": rows}


def render() -> str:
    return HEADER + yaml.safe_dump(build(), sort_keys=False, allow_unicode=True, width=200)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the catalog is stale")
    args = ap.parse_args()
    text = render()
    rel = TARGET.relative_to(REPO)
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print(f"model-catalog-gen: {rel} is stale; run tools/model-catalog-gen.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {rel} ({len(build()['rows'])} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
