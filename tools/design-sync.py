#!/usr/bin/env python3
"""Vendor the AIT design tokens and regenerate what derives from them.

    tools/design-sync.py ../design        # copy tokens.json, regenerate tools/cc/theme.py
    tools/design-sync.py --check          # regenerate from the vendored copy, diff only

Source of truth is thisisait/design; this repo keeps a pinned copy because a converge
never fetches. The nos-cc theme is generated, never hand-edited: the gate
tests/anatomy/test_cc_theme_is_design_tokens.py fails when the two disagree.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VENDORED = REPO / "files/anatomy/design/tokens.json"
README = REPO / "files/anatomy/design/README.md"
THEME_PY = REPO / "tools/cc/theme.py"
THEME_ID = "glass-face"

# Textual Theme field -> design token. A terminal has no translucency, so the
# glass panel is composited over the canvas by hand (see `solid`).
FIELDS = {
    "primary": "accent-hi", "secondary": "accent-soft", "accent": "accent",
    "foreground": "ink", "background": "canvas", "surface": "panel", "panel": "raise",
    "success": "ok", "warning": "warn", "error": "signal",
}


def _hex(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def solid(value: str, ground: str) -> str:
    """rgba(...) composited over an opaque hex ground; hex passes through."""
    m = re.fullmatch(r"rgba\((\d+), (\d+), (\d+), ([\d.]+)\)", value)
    if not m:
        return value
    a = float(m[4])
    g = _hex(ground)
    rgb = [round(int(m[i + 1]) * a + g[i] * (1 - a)) for i in range(3)]
    return "#" + "".join(f"{c:02x}" for c in rgb)


def theme_values(tokens: dict, theme: str = THEME_ID) -> dict[str, str]:
    colors = {c["name"]: c["value"][theme] for c in tokens["color"]["tokens"]}
    canvas = colors["canvas"]
    return {field: solid(colors[tok], canvas) for field, tok in FIELDS.items()}


def render_theme(tokens: dict, sha: str) -> str:
    vals = theme_values(tokens)
    body = "\n".join(f'    {k}="{v}",' for k, v in vals.items())
    return f'''"""GENERATED by tools/design-sync.py from files/anatomy/design/tokens.json — do not edit.

The nos-cc colours are the design system's `{THEME_ID}` theme (thisisait/design@{sha}),
so the terminal control centre and the face desktop read as one estate.
"""

THEME_NAME = "ait-{THEME_ID}"
SOURCE = "thisisait/design@{sha}"
VALUES = dict(
{body}
)


def register(app) -> None:
    """Install the theme on a Textual App and make it the default.

    Older Textual releases have no Theme API; then the built-in theme stays and
    nothing else changes — the readers never depend on colour.
    """
    try:
        from textual.theme import Theme
    except ImportError:  # textual < 0.86
        return
    app.register_theme(Theme(name=THEME_NAME, dark=True, **VALUES))
    app.theme = THEME_NAME
'''


def sha_of(path: Path) -> str:
    out = subprocess.run(["git", "-C", str(path), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("design", nargs="?", help="path to a thisisait/design checkout")
    ap.add_argument("--check", action="store_true", help="diff only, exit 1 on drift")
    args = ap.parse_args()
    if args.design:
        src = Path(args.design)
        sha = sha_of(src)
        VENDORED.write_text((src / "tokens/tokens.json").read_text())
        README.write_text(re.sub(r"commit `[0-9a-f]+`", f"commit `{sha}`", README.read_text()))
    m = re.search(r"commit `([0-9a-f]+)`", README.read_text())
    sha = m[1] if m else "unknown"
    rendered = render_theme(json.loads(VENDORED.read_text()), sha)
    if args.check:
        if THEME_PY.read_text() != rendered:
            print(f"{THEME_PY.relative_to(REPO)} is stale: run tools/design-sync.py", file=sys.stderr)
            return 1
        print("design: in sync")
        return 0
    THEME_PY.write_text(rendered)
    print(f"wrote {THEME_PY.relative_to(REPO)} from design@{sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
