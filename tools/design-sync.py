#!/usr/bin/env python3
"""Vendor the AIT design tokens and regenerate what derives from them.

    tools/design-sync.py ../design        # copy tokens.json + components.css, regenerate
    tools/design-sync.py --check          # regenerate from the vendored copy, diff only

Source of truth is thisisait/design; this repo keeps a pinned copy because a converge
never fetches. Generated, never hand-edited: the nos-cc theme (gate
test_cc_theme_is_design_tokens.py) and the face's tokens.css (test_face_tokens_are_design_tokens.py).
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VENDORED = REPO / "files/anatomy/design/tokens.json"
VENDORED_CSS = REPO / "files/anatomy/design/components.css"
README = REPO / "files/anatomy/design/README.md"
THEME_PY = REPO / "tools/cc/theme.py"
FACE_CSS = REPO / "files/anatomy/face/src/lib/design/tokens.css"
THEME_ID = "glass-face"

# Textual Theme field -> design token. A terminal has no translucency, so the
# glass panel is composited over the canvas by hand (see `solid`).
FIELDS = {
    "primary": "accent-hi", "secondary": "accent-soft", "accent": "accent",
    "foreground": "ink", "background": "canvas", "surface": "panel", "panel": "raise",
    "success": "ok", "warning": "warn", "error": "signal",
}


# Face variable -> design token: the face keeps its names, the design sets the values.
# Face names with no design token (ok/warn/bad -soft and -ink) are derived in app.css.
FACE = {
    "--bg": "canvas", "--fg": "ink", "--muted": "ink-dim",
    "--glass": "panel", "--glass-brd": "line", "--accent": "accent-hi",
    "--ok": "ok", "--info": "accent-hi", "--warn": "warn", "--bad": "signal",
    "--info-soft": "accent-faint", "--info-ink": "accent-soft",
}


def _hex(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def solid(value: str, ground: str) -> str:
    """rgba(...) composited over an opaque hex ground; hex passes through."""
    m = re.fullmatch(r"rgba\((\d+), (\d+), (\d+), ([\d.]+)\)", value)
    if not m:
        return value
    a = float(m[4])
    g = _hex(ground)
    rgb = [round(int(m[i + 1]) * a + g[i] * (1 - a)) for i in range(3)]
    return "#" + "".join(f"{c:02x}" for c in rgb)


def theme_values(tokens: dict, theme: str = THEME_ID) -> dict[str, str]:
    colors = {c["name"]: c["value"][theme] for c in tokens["color"]["tokens"]}
    canvas = colors["canvas"]
    return {field: solid(colors[tok], canvas) for field, tok in FIELDS.items()}


def render_theme(tokens: dict, sha: str) -> str:
    vals = theme_values(tokens)
    body = "\n".join(f'    {k}="{v}",' for k, v in vals.items())
    return f'''"""GENERATED by tools/design-sync.py from files/anatomy/design/tokens.json — do not edit.

The nos-cc colours are the design system's `{THEME_ID}` theme (thisisait/design@{sha}),
so the terminal control centre and the face desktop read as one estate.
"""

THEME_NAME = "ait-{THEME_ID}"
SOURCE = "thisisait/design@{sha}"
VALUES = dict(
{body}
)


def register(app) -> None:
    """Install the theme on a Textual App and make it the default.

    Older Textual releases have no Theme API; then the built-in theme stays and
    nothing else changes — the readers never depend on colour.
    """
    try:
        from textual.theme import Theme
    except ImportError:  # textual < 0.86
        return
    app.register_theme(Theme(name=THEME_NAME, dark=True, **VALUES))
    app.theme = THEME_NAME
'''


def glass_filter(css: str) -> str:
    """tokens.json has no effect group: the glass blur+saturate is the design CSS's one rule."""
    return re.search(r"\bbackdrop-filter:\s*([^;]+);", css)[1].strip()


def render_face_css(tokens: dict, css: str, sha: str) -> str:
    colors = {c["name"]: c["value"][THEME_ID] for c in tokens["color"]["tokens"]}
    body = "\n".join(f"\t{k}: {colors[t]}; /* {t} */" for k, t in FACE.items())
    return f"""/* GENERATED by tools/design-sync.py from files/anatomy/design/ — do not edit.
   The face's colours are the design system's `{THEME_ID}` theme (thisisait/design@{sha});
   each face name carries the design token it aliases. Gate: test_face_tokens_are_design_tokens.py. */
:root {{
{body}
\t--glass-filter: {glass_filter(css)}; /* components-css */
}}
"""


def sha_of(path: Path) -> str:
    out = subprocess.run(["git", "-C", str(path), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("design", nargs="?", help="path to a thisisait/design checkout")
    ap.add_argument("--check", action="store_true", help="diff only, exit 1 on drift")
    args = ap.parse_args()
    if args.design:
        src = Path(args.design)
        sha = sha_of(src)
        VENDORED.write_text((src / "tokens/tokens.json").read_text())
        VENDORED_CSS.write_text((src / "src/css/components.css").read_text())
        README.write_text(re.sub(r"commit `[0-9a-f]+`", f"commit `{sha}`", README.read_text()))
    m = re.search(r"commit `([0-9a-f]+)`", README.read_text())
    sha = m[1] if m else "unknown"
    tokens = json.loads(VENDORED.read_text())
    out = {THEME_PY: render_theme(tokens, sha),
           FACE_CSS: render_face_css(tokens, VENDORED_CSS.read_text(), sha)}
    if args.check:
        stale = [p for p, text in out.items() if not p.is_file() or p.read_text() != text]
        for p in stale:
            print(f"{p.relative_to(REPO)} is stale: run tools/design-sync.py", file=sys.stderr)
        if stale:
            return 1
        print("design: in sync")
        return 0
    for p, text in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(REPO)} from design@{sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
